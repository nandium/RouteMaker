import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { BRAND_PALETTE, LOGO_MARK_SEGMENTS, logoMarkPaths } from '../src/brand.ts';

const variants = [
  ['app_icon', BRAND_PALETTE.light],
  ['app_icon_dark', BRAND_PALETTE.dark],
];

function launcherSvg(palette, round = false) {
  const clip = round
    ? '<defs><clipPath id="icon-mask"><circle cx="512" cy="512" r="512"/></clipPath></defs><g clip-path="url(#icon-mask)">'
    : '';
  const closeClip = round ? '  </g>\n' : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">${clip}
  <rect width="1024" height="1024" fill="${palette.background}"/>
  <g fill="${palette.primary}" transform="translate(256 211) scale(1.47)">${logoMarkPaths(palette.secondary)}
  </g>
${closeClip}</svg>
`;
}

for (const [name, palette] of variants) {
  const svg = launcherSvg(palette);
  const svgPath = new URL(`../resource/${name}.svg`, import.meta.url);
  const pngPath = new URL(`../resource/${name}.png`, import.meta.url);
  writeFileSync(svgPath, `<!-- Generated by npm run brand:assets. -->\n${svg}`);
  execFileSync('rsvg-convert', ['--output', pngPath.pathname, svgPath.pathname]);
}

const resource = new URL('../resource/', import.meta.url);
const iosIcons = new URL(
  '../ios/RouteMaker/RouteMaker/Assets.xcassets/AppIcon.appiconset/',
  import.meta.url
);
copyFileSync(new URL('app_icon.png', resource), new URL('RouteMaker.png', iosIcons));
copyFileSync(new URL('app_icon_dark.png', resource), new URL('RouteMaker-dark.png', iosIcons));

const androidForeground = `<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="0.16"
        android:scaleY="0.16"
        android:translateX="26"
        android:translateY="22">
${LOGO_MARK_SEGMENTS.map(
  ({ path, tone }) =>
    `        <path android:fillColor="${BRAND_PALETTE.light[tone]}" android:pathData="${path}" />`
).join('\n')}
    </group>
</vector>
`;
const androidBackground = `<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="${BRAND_PALETTE.light.background}"
        android:pathData="M0,0h108v108h-108z" />
</vector>
`;
const androidDrawable = new URL('../android/app/src/main/res/drawable/', import.meta.url);
writeFileSync(new URL('ic_launcher_foreground.xml', androidDrawable), androidForeground);
writeFileSync(new URL('ic_launcher_background.xml', androidDrawable), androidBackground);

const densities = [
  ['mdpi', 48],
  ['hdpi', 72],
  ['xhdpi', 96],
  ['xxhdpi', 144],
  ['xxxhdpi', 192],
];
const temporaryDirectory = mkdtempSync(join(tmpdir(), 'routemaker-icons-'));
const roundSvg = join(temporaryDirectory, 'round.svg');
writeFileSync(roundSvg, launcherSvg(BRAND_PALETTE.light, true));
try {
  for (const [density, size] of densities) {
    const destination = new URL(`../android/app/src/main/res/mipmap-${density}/`, import.meta.url);
    for (const [source, filename] of [
      [new URL('app_icon.svg', resource).pathname, 'ic_launcher.webp'],
      [roundSvg, 'ic_launcher_round.webp'],
    ]) {
      const png = join(temporaryDirectory, `${density}-${filename}.png`);
      execFileSync('rsvg-convert', [
        '--width',
        `${size}`,
        '--height',
        `${size}`,
        '--output',
        png,
        source,
      ]);
      execFileSync('cwebp', ['-quiet', png, '-o', new URL(filename, destination).pathname]);
    }
  }
} finally {
  rmSync(temporaryDirectory, { force: true, recursive: true });
}

const generatedAssets = [
  'resource/app_icon.svg',
  'resource/app_icon.png',
  'resource/app_icon_dark.svg',
  'resource/app_icon_dark.png',
  'ios/RouteMaker/RouteMaker/Assets.xcassets/AppIcon.appiconset/RouteMaker.png',
  'ios/RouteMaker/RouteMaker/Assets.xcassets/AppIcon.appiconset/RouteMaker-dark.png',
  'android/app/src/main/res/drawable/ic_launcher_foreground.xml',
  'android/app/src/main/res/drawable/ic_launcher_background.xml',
  ...densities.flatMap(([density]) => [
    `android/app/src/main/res/mipmap-${density}/ic_launcher.webp`,
    `android/app/src/main/res/mipmap-${density}/ic_launcher_round.webp`,
  ]),
];
const appRoot = new URL('../', import.meta.url);
const digest = (value) => createHash('sha256').update(value).digest('hex');
const manifest = {
  source: digest(`${JSON.stringify(BRAND_PALETTE)}${JSON.stringify(LOGO_MARK_SEGMENTS)}`),
  files: Object.fromEntries(
    generatedAssets.map((path) => [path, digest(readFileSync(new URL(path, appRoot)))])
  ),
};
writeFileSync(
  new URL('../resource/brand-assets.json', import.meta.url),
  `${JSON.stringify(manifest, null, 2)}\n`
);
